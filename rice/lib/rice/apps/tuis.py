"""TUIs that read their theme at startup: lazygit, gitui, yazi."""
import re

from .. import paths as paths_mod
from .. import util

OLD_HEADER = "# GENERATED by rice: edit ~/dotfiles/rice/config/lazygit-base.yml instead\n"


def _indent(line):
    return len(line) - len(line.lstrip(" "))


def _blank(line):
    s = line.strip()
    return not s or s.startswith("#")


def lazygit_set_theme(text, theme_yml):
    """config.yml with gui.theme replaced by the theme file's, every other line kept.

    Plain line editing (no YAML library on a stock system): the root `gui:` mapping
    is found by indentation and only its `theme:` child is replaced. A `gui:` written
    in flow style ({...}) is refused rather than guessed at."""
    # The theme file is `gui:` + an indented `theme:` block: take that block, dedented.
    lines = theme_yml.splitlines()
    start = next((i for i, ln in enumerate(lines) if re.match(r"^gui:\s*(#.*)?$", ln)), None)
    block = [ln for ln in (lines[start + 1:] if start is not None else []) if ln.strip()]
    if not block or not block[0].lstrip().startswith("theme:"):
        raise util.ConfigEditError("lazygit.yml has no gui.theme block")
    base = _indent(block[0])
    block = [ln[base:] if _indent(ln) >= base else ln.lstrip() for ln in block]

    text = text.replace(OLD_HEADER, "", 1)
    out = text.splitlines()
    gui = next((i for i, ln in enumerate(out) if re.match(r"^gui:", ln)), None)
    if gui is None:
        out = [*out, *(["" ] if out and out[-1].strip() else []), "gui:", *("  " + ln for ln in block)]
        return "\n".join(out).lstrip("\n") + "\n"
    if not re.match(r"^gui:\s*(#.*)?$", out[gui]):
        raise util.ConfigEditError("gui: is written inline; add the theme yourself")
    # gui's children: until the next line back at column 0.
    end = next((i for i in range(gui + 1, len(out)) if not _blank(out[i]) and _indent(out[i]) == 0), len(out))
    children = [i for i in range(gui + 1, end) if not _blank(out[i])]
    step = _indent(out[children[0]]) if children else 2
    pad = " " * step
    kept, i = [], gui + 1
    while i < end:
        ln = out[i]
        if not _blank(ln) and _indent(ln) == step and re.match(r"^theme:", ln.lstrip()):
            i += 1  # the old theme: everything deeper than it goes too
            while i < end and (_blank(out[i]) or _indent(out[i]) > step):
                if _blank(out[i]) and out[i].strip() and _indent(out[i]) <= step:
                    break  # a comment back at gui's level belongs to the next key
                i += 1
            continue
        kept.append(ln)
        i += 1
    new = out[:gui + 1] + [pad + ln for ln in block] + kept + out[end:]
    return "\n".join(new) + "\n"


def lazygit(ctx):
    """Only gui.theme changes: keybindings, custom commands and the rest stay yours.
    A config.yml that doesn't exist yet starts from rice/config/lazygit-base.yml."""
    theme = ctx.file("lazygit.yml")
    cfg_dir = ctx.paths.config / "lazygit"
    if not theme or not cfg_dir.is_dir():
        return
    cfg = cfg_dir / "config.yml"
    if cfg.is_file():
        text = cfg.read_text()
    else:
        base_file = paths_mod.ROOT / "config" / "lazygit-base.yml"
        text = base_file.read_text() if base_file.is_file() else ""
    new = lazygit_set_theme(text, theme.read_text())
    try:
        import yaml
    except ImportError:
        yaml = None
    if yaml is not None:
        try:
            ok = isinstance(yaml.safe_load(new), dict)
        except yaml.YAMLError:
            ok = False
        if not ok:
            raise util.ConfigEditError("the edited config.yml wouldn't parse; left alone")
    if new != text:
        # A symlinked config.yml (into a dotfiles repo) becomes a real file, so theme
        # colours don't show up as changes there.
        util.atomic_write(cfg, new, follow=False)


def gitui(ctx):
    theme = ctx.file("gitui.ron")
    if theme and (ctx.paths.config / "gitui").is_dir():
        util.install_file(theme, ctx.paths.config / "gitui" / "theme.ron")


YAZI_HEADER = "# Written by rice: the flavor is the current theme (~/.local/state/rice/current/theme/yazi.toml).\n"
FLAVOR_TABLE = re.compile(r"(?ms)^[ \t]*\[[ \t]*flavor[ \t]*\][^\n]*\n?.*?(?=^[ \t]*\[|\Z)")


def yazi_set_flavor(text):
    """theme.toml with [flavor] dark/light = "rice" and everything else kept."""
    import tomllib
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise util.ConfigEditError(f"not valid TOML ({e}); left alone") from None
    if data.get("flavor") == {"dark": "rice", "light": "rice"}:
        return text
    body = FLAVOR_TABLE.sub("", text.replace(YAZI_HEADER, ""))
    # Keys before the first table stay there (after [flavor] they'd move into it).
    first = re.search(r"(?m)^[ \t]*\[", body)
    root, tables = (body[:first.start()], body[first.start():]) if first else (body, "")
    root, tables = root.strip("\n"), tables.strip("\n")
    new = (YAZI_HEADER + (root + "\n\n" if root else "") + '[flavor]\ndark  = "rice"\nlight = "rice"\n'
           + ("\n" + tables + "\n" if tables else ""))
    try:
        check = tomllib.loads(new)
    except tomllib.TOMLDecodeError as e:
        raise util.ConfigEditError(f"the edit wouldn't parse ({e}); left alone") from None
    if check.get("flavor", {}).get("dark") != "rice":
        raise util.ConfigEditError("the edit didn't take; left alone")
    return new


def yazi(ctx):
    flavor = ctx.file("yazi.toml")
    cfg = ctx.paths.config / "yazi"
    if not flavor or not cfg.is_dir():
        return
    util.install_file(flavor, cfg / "flavors" / "rice.yazi" / "flavor.toml")
    theme = cfg / "theme.toml"
    text = theme.read_text() if theme.is_file() else ""
    new = yazi_set_flavor(text)
    if new != text:
        util.atomic_write(theme, new)
