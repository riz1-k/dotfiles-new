"""TUIs that read their theme at startup: lazygit, gitui, yazi."""
import re

from .. import paths as paths_mod
from .. import util

HEADER = "# GENERATED by rice: edit ~/dotfiles/rice/config/lazygit-base.yml instead\n"


def lazygit(ctx):
    theme = ctx.file("lazygit.yml")
    cfg_dir = ctx.paths.config / "lazygit"
    if not theme or not cfg_dir.is_dir():
        return
    base_file = paths_mod.ROOT / "config" / "lazygit-base.yml"
    base = base_file.read_text() if base_file.is_file() else ""
    # The theme file is `gui:` + an indented `theme:` block; nest it under the
    # base config's own gui: mapping (YAML has no duplicate keys).
    block = re.sub(r"(?s)^.*?^gui:\s*\n", "", theme.read_text(), count=1, flags=re.M)
    if re.search(r"(?m)^gui:\s*$", base):
        text = re.sub(r"(?m)^gui:\s*$", "gui:\n" + block.rstrip("\n"), base, count=1)
    else:
        text = base.rstrip("\n") + ("\n" if base else "") + "gui:\n" + block
    util.atomic_write(cfg_dir / "config.yml", HEADER + text.rstrip("\n") + "\n", follow=False)


def gitui(ctx):
    theme = ctx.file("gitui.ron")
    if theme and (ctx.paths.config / "gitui").is_dir():
        util.install_file(theme, ctx.paths.config / "gitui" / "theme.ron")


def yazi(ctx):
    flavor = ctx.file("yazi.toml")
    cfg = ctx.paths.config / "yazi"
    if not flavor or not cfg.is_dir():
        return
    util.install_file(flavor, cfg / "flavors" / "rice.yazi" / "flavor.toml")
    theme = cfg / "theme.toml"
    want = '[flavor]\ndark  = "rice"\nlight = "rice"\n'
    text = theme.read_text() if theme.is_file() else ""
    if 'dark  = "rice"' not in text:
        body = re.sub(r"(?ms)^\[flavor\].*?(?=^\[|\Z)", "", text).strip("\n")
        header = "# Written by rice: the flavor is the current theme (~/.local/state/rice/current/theme/yazi.toml).\n"
        util.atomic_write(theme, header + want + ("\n" + body + "\n" if body and not body.startswith("#") else ""))
